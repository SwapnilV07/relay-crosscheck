#!/usr/bin/env node
"use strict";
/*
 * Builds docs/crosscheck.js, the browser copy of the engine used by the web app (docs/index.html).
 * It wraps the same files in src/ that the command line uses, so both always give the same answers.
 *
 *   node scripts/build-web.js          write the bundle
 *   node scripts/build-web.js --check  exit 1 if the bundle is out of date (run by the tests)
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "docs", "crosscheck.js");
const MODULES = ["rules", "scan-core", "engine", "health", "report", "api", "ticket"];
const EXAMPLE_APP = path.join(ROOT, "test", "fixtures", "legacy-app");

function listFiles(dir, base = dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(d => {
    const p = path.join(dir, d.name);
    return d.isDirectory() ? listFiles(p, base) : [path.relative(base, p).split(path.sep).join("/")];
  }).sort();
}

function build() {
  const pkg = require(path.join(ROOT, "package.json"));
  const example = listFiles(EXAMPLE_APP).map(p => ({ path: p, text: fs.readFileSync(path.join(EXAMPLE_APP, p), "utf8") }));
  const pumpfun = fs.readFileSync(path.join(ROOT, "examples", "pumpfun-relay-ab-daily.csv"), "utf8");
  let out = "/* Relay Crosscheck " + pkg.version + " for the browser. Generated by scripts/build-web.js from src/. Do not edit by hand. */\n";
  out += "(function (global) {\n\"use strict\";\nconst __defs = {}, __cache = {};\n";
  out += "function require(name) { const k = name.replace(/^\\.\\//, \"\"); if (__cache[k]) return __cache[k].exports; if (!__defs[k]) throw new Error(\"Module not bundled: \" + name); const module = { exports: {} }; __cache[k] = module; __defs[k](module, module.exports, require); return module.exports; }\n";
  for (const m of MODULES) {
    const src = fs.readFileSync(path.join(ROOT, "src", m + ".js"), "utf8");
    out += "__defs[" + JSON.stringify(m) + "] = function (module, exports, require) {\n" + src.replace(/^"use strict";\n/, "") + "\n};\n";
  }
  out += "global.RelayCrosscheck = {\n";
  out += "  version: " + JSON.stringify(pkg.version) + ",\n";
  out += "  scan: require(\"scan-core\"), rules: require(\"rules\"), engine: require(\"engine\"), health: require(\"health\"),\n";
  out += "  report: require(\"report\"), api: require(\"api\"), ticket: require(\"ticket\"),\n";
  out += "  examples: { legacyApp: " + JSON.stringify(example) + ",\n    pumpfunDailyCsv: " + JSON.stringify(pumpfun) + " },\n";
  out += "};\n})(typeof window !== \"undefined\" ? window : globalThis);\n";
  return out;
}

/* index.html loads app.css, app.js and crosscheck.js with ?v=<content hash>, so a browser never mixes
   a new page with an old cached script after an update. */
function stamp(html, bundle) {
  const crypto = require("crypto");
  const hash = text => crypto.createHash("sha256").update(text).digest("hex").slice(0, 10);
  const read = f => (f === "crosscheck.js" ? bundle : fs.readFileSync(path.join(ROOT, "docs", f), "utf8"));
  return html.replace(/(src|href)="(app\.css|app\.js|crosscheck\.js)(\?v=[0-9a-f]+)?"/g, (_, attr, f) => `${attr}="${f}?v=${hash(read(f))}"`);
}
const INDEX = path.join(ROOT, "docs", "index.html");

if (require.main === module) {
  const fresh = build();
  const html = fs.readFileSync(INDEX, "utf8"), stamped = stamp(html, fresh);
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== fresh || html !== stamped) { console.error("docs/crosscheck.js or the file versions in docs/index.html are out of date. Run: node scripts/build-web.js"); process.exit(1); }
    console.log("docs/crosscheck.js is up to date.");
  } else {
    fs.writeFileSync(OUT, fresh);
    fs.writeFileSync(INDEX, stamped);
    console.log("Wrote " + path.relative(process.cwd(), OUT) + " (" + Math.round(fresh.length / 1024) + " KB)");
  }
}

module.exports = { build, stamp, OUT, INDEX };
